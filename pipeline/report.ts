// Renders the human-readable reports in data/reports/. Output must be deterministic.
import type { BuildResult, ValidationRow } from "./dataset.ts";

const short = (sha: string): string => sha.slice(0, 7);

function header(title: string, r: BuildResult): string {
  return [
    `# ${title}`,
    "",
    `Generated by \`npm run build:data\` from PokéAPI \`${short(r.lock.pokeapi.commit)}\` and PvPoke \`${short(r.lock.pvpoke.commit)}\`. Do not edit by hand.`,
    "",
  ].join("\n");
}

const line = (s: { atk: number; def: number; sta: number }): string => `${s.atk}/${s.def}/${s.sta}`;

function delta(row: ValidationRow): string {
  const d = (k: "atk" | "def" | "sta"): string => {
    const v = row.actual[k] - row.predicted[k];
    return v === 0 ? "0" : v > 0 ? `+${v}` : `${v}`;
  };
  return `${d("atk")}/${d("def")}/${d("sta")}`;
}

function adjustment(row: ValidationRow): string {
  const s = row.predicted.steps;
  return s.adjustmentReason === "none" ? "×1" : `×${s.adjustment} (${s.adjustmentReason})`;
}

const escape = (s: string): string => s.replace(/\|/g, "\\|");

export function renderValidation(r: BuildResult): string {
  const v = r.validation;
  const total = v.exact.length + v.exceptions.length + v.unexplained.length;
  const pct = (n: number): string => (total ? `${((n / total) * 100).toFixed(1)}%` : "–");
  const out = [
    header("Formula validation", r),
    "Every dataset entry with GO data, comparing PvPoke's GO stats with the formula's prediction (`src/lib/formula.ts`).",
    "",
    "| Result | Entries | Share |",
    "|---|---:|---:|",
    `| Exact match | ${v.exact.length} | ${pct(v.exact.length)} |`,
    `| Listed exception | ${v.exceptions.length} | ${pct(v.exceptions.length)} |`,
    `| **Unexplained** | **${v.unexplained.length}** | ${pct(v.unexplained.length)} |`,
    "",
  ];

  const adjCounts = new Map<string, number>();
  const eraCount = r.dataset.pokemon.filter((p) => p.msGoBasis).length;
  for (const p of r.dataset.pokemon) {
    const s = p.goPredicted.steps;
    const key = s.adjustmentReason === "none" ? "×1" : `×${s.adjustment} (${s.adjustmentReason})`;
    adjCounts.set(key, (adjCounts.get(key) ?? 0) + 1);
  }
  out.push("Adjustments applied across the whole dataset:", "", "| Adjustment | Entries |", "|---|---:|");
  for (const [k, n] of [...adjCounts].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))) out.push(`| ${k} | ${n} |`);
  out.push("", `Entries converted from an older stat era (\`msGoBasis\`): ${eraCount}.`, "");

  out.push("## Unexplained mismatches", "");
  if (v.unexplained.length === 0) {
    out.push("None.", "");
  } else {
    out.push(
      "Each needs a reason in `data/overrides.yaml` (`exceptions`, `basisGeneration` or `fixedAdjustment`), or a formula fix.",
      "",
      "| Id | PvPoke id | GO actual | Predicted | Actual − predicted | Stat era | Adjustment | Note |",
      "|---|---|---|---|---|---|---|---|",
    );
    for (const row of v.unexplained) {
      out.push(
        `| ${row.id} | ${row.goId} | ${line(row.actual)} | ${line(row.predicted)} | ${delta(row)} | Gen ${row.basisGen} | ${adjustment(row)} | ${escape(row.note ?? "")} |`,
      );
    }
    out.push("");
  }

  out.push("## Listed exceptions", "");
  if (v.exceptions.length === 0) {
    out.push("None.", "");
  } else {
    out.push("| Id | GO actual | Predicted | Reason | Source |", "|---|---|---|---|---|");
    for (const row of v.exceptions) {
      out.push(`| ${row.id} | ${line(row.actual)} | ${line(row.predicted)} | ${escape(row.reason ?? "")} | ${escape(row.source ?? "")} |`);
    }
    out.push("");
  }
  return out.join("\n");
}

export function renderCoverage(r: BuildResult): string {
  const c = r.coverage;
  const methods = new Map<string, number>();
  for (const m of c.join.matches) methods.set(m.method, (methods.get(m.method) ?? 0) + 1);
  const out = [
    header("Coverage", r),
    "## Main-series forms (PokéAPI)",
    "",
    "| Step | Forms |",
    "|---|---:|",
    `| All PokéAPI \`pokemon\` rows | ${c.msTotal} |`,
    `| Excluded by \`excludeForms\` | ${c.excluded.length} |`,
    `| Dropped as duplicate stats | ${c.dropped.length} |`,
    `| **In the dataset** | **${r.dataset.counts.total}** |`,
    `| …with GO data | ${r.dataset.counts.actual} |`,
    `| …predicted only | ${r.dataset.counts.predicted} |`,
    "",
    "## GO entries (PvPoke)",
    "",
    "| Step | Entries |",
    "|---|---:|",
    `| All PvPoke entries | ${c.pvpoke.totalRaw} |`,
    `| Shadow entries (folded into \`shadowAvailable\`) | ${c.pvpoke.shadowCount} |`,
    `| Ignored by \`ignoreGo\` | ${c.join.ignored.length} |`,
    `| Matched: exact id | ${methods.get("exact") ?? 0} |`,
    `| Matched: species default form | ${methods.get("default-form") ?? 0} |`,
    `| Matched: \`idMap\` | ${methods.get("idMap") ?? 0} |`,
    `| **Unmatched (build fails)** | **${c.join.unmatched.length}** |`,
    `| **Conflicting (build fails)** | **${c.join.conflicts.length}** |`,
    "",
  ];

  if (c.join.unmatched.length > 0) {
    out.push("### Unmatched PvPoke entries", "", "| PvPoke id | Dex | Name |", "|---|---:|---|");
    for (const g of c.join.unmatched) out.push(`| ${g.goId} | ${g.dex} | ${escape(g.name)} |`);
    out.push("");
  }

  if (c.join.conflicts.length > 0) {
    out.push("### Conflicting PvPoke entries", "", "| PvPoke id | Matched | Already taken by |", "|---|---|---|");
    for (const k of c.join.conflicts) out.push(`| ${k.go.goId} | ${k.msId} | ${k.takenBy} |`);
    out.push("");
  }

  out.push("### Ignored PvPoke entries", "", "| PvPoke id | Reason |", "|---|---|");
  for (const { go, reason } of c.join.ignored) out.push(`| ${go.goId} | ${escape(reason)} |`);
  out.push("");

  const nonExact = c.join.matches.filter((m) => m.method !== "exact");
  out.push("### Matches that needed a rule", "", "| PvPoke id | PokéAPI id | Rule |", "|---|---|---|");
  for (const m of nonExact) out.push(`| ${m.go.goId} | ${m.msId} | ${m.method} |`);
  out.push("");

  out.push("## Excluded and dropped forms", "", "| PokéAPI id | Reason |", "|---|---|");
  for (const e of [...c.excluded, ...c.dropped].sort((a, b) => a.id.localeCompare(b.id))) out.push(`| ${e.id} | ${escape(e.reason)} |`);
  out.push("");

  out.push("## Forms with no GO data (stats predicted)", "", c.predictedIds.map((id) => `\`${id}\``).join(", ") || "None.", "");
  return out.join("\n");
}
